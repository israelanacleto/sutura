-- Fase 3 — prevenção de glosa de cadastro.
--
-- A decisão que sustenta este schema: a guia carrega uma CÓPIA PRÓPRIA dos dados do
-- paciente. Nome, CNS, CPF e carteirinha são gravados na guia no momento da emissão,
-- digitados ou copiados de algum sistema.
--
-- É essa cópia que diverge do cadastro real, e é a divergência que gera glosa. Sem
-- guardar os dados na própria guia não haveria o que comparar — o modelo inteiro
-- depende disso.

CREATE TABLE guia_faturamento (
  id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registro_origem_id  NUMBER        NOT NULL,
  evento_clinico_id   NUMBER,
  numero_guia         VARCHAR2(30)  NOT NULL,
  procedimento        VARCHAR2(200) NOT NULL,
  convenio            VARCHAR2(120),
  carteirinha         VARCHAR2(40),

  -- A cópia dos dados do paciente, como constam NA GUIA.
  -- Não são os dados do cadastro: são os que o faturamento vai enviar à operadora.
  nome_paciente       VARCHAR2(200) NOT NULL,
  cns_paciente        VARCHAR2(20),
  cpf_paciente        VARCHAR2(14),
  nascimento_paciente DATE,

  valor               NUMBER(12, 2) NOT NULL,
  data_emissao        DATE          NOT NULL,
  status              VARCHAR2(20)  DEFAULT 'PRONTA' NOT NULL,

  CONSTRAINT fk_guia_registro FOREIGN KEY (registro_origem_id) REFERENCES registro_origem (id),
  CONSTRAINT fk_guia_evento   FOREIGN KEY (evento_clinico_id)  REFERENCES evento_clinico (id),
  CONSTRAINT uk_guia_numero   UNIQUE (numero_guia),
  CONSTRAINT ck_guia_status   CHECK (status IN ('RASCUNHO', 'PRONTA', 'ENVIADA'))
);

-- Índices nas chaves estrangeiras. Lição da V7: sem eles, apagar uma linha da tabela pai
-- leva o Oracle a tomar bloqueio mais abrangente na filha.
CREATE INDEX ix_guia_registro ON guia_faturamento (registro_origem_id);
CREATE INDEX ix_guia_evento ON guia_faturamento (evento_clinico_id);

COMMENT ON TABLE guia_faturamento IS 'Guia como o faturamento a emitiu, com a cópia dos dados do paciente no momento da emissão';
COMMENT ON COLUMN guia_faturamento.nome_paciente IS 'O nome COMO CONSTA NA GUIA — pode divergir do cadastro unificado, e é essa divergência que gera glosa';

-- As regras vivem em tabela, não em código. Permite desligar uma regra sem migration, e
-- deixa a lista visível para quem opera o sistema.
CREATE TABLE regra_glosa (
  codigo     VARCHAR2(40)  PRIMARY KEY,
  descricao  VARCHAR2(300) NOT NULL,
  orientacao VARCHAR2(300),
  severidade VARCHAR2(10)  NOT NULL,
  ativo      NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT ck_regra_severidade CHECK (severidade IN ('ALTA', 'MEDIA', 'BAIXA')),
  CONSTRAINT ck_regra_ativo CHECK (ativo IN (0, 1))
);

-- Auditoria da correção. Uma linha por campo alterado: guia com três campos errados gera
-- três linhas. É assim que se responde "o que exatamente mudou nesta guia, e quem mudou".
CREATE TABLE correcao_guia (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guia_id        NUMBER        NOT NULL,
  campo          VARCHAR2(40)  NOT NULL,
  valor_anterior VARCHAR2(200),
  valor_novo     VARCHAR2(200),
  usuario        VARCHAR2(80)  NOT NULL,
  corrigido_em   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_correcao_guia FOREIGN KEY (guia_id) REFERENCES guia_faturamento (id)
);

CREATE INDEX ix_correcao_guia ON correcao_guia (guia_id);

COMMENT ON TABLE correcao_guia IS 'Auditoria: quem corrigiu que campo da guia, de qual valor para qual, e quando';

